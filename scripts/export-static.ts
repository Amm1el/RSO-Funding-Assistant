// Packs the corpus for the phone/static build: every chunk (with section, title and link),
// the directory, and counts, gzipped and base64-encoded into web/src/generated/corpus-data.ts.
// Usage: npx tsx scripts/export-static.ts [--dir data/corpus] [--meeting-months 6]
import { mkdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { DEFAULT_CORPUS_DIR, loadCorpus, manualAsDoc } from "../src/corpus/load.js";
import { chunkCorpus } from "../src/corpus/ingest.js";
import { buildDirectory } from "../src/corpus/directory.js";
import { COLLECTIONS } from "../src/corpus/collections.js";

const args = process.argv.slice(2);
const flag = (n: string) => (args.includes(n) ? args[args.indexOf(n) + 1] : undefined);
const dir = flag("--dir") ?? DEFAULT_CORPUS_DIR;
// Old meetings are the bulk of the corpus and the least useful on a phone.
const meetingMonths = Number(flag("--meeting-months") ?? 6);

let docs = await loadCorpus(dir);
if (!docs.length) {
  if (!existsSync("data/26-27SGAFM.pdf")) throw new Error("No corpus and no manual PDF.");
  docs = [await manualAsDoc("data/26-27SGAFM.pdf")];
}
const cutoff = new Date(Date.now() - meetingMonths * 30.5 * 86400_000).toISOString();
const kept = docs.filter((d) => d.kind !== "meeting" || String(d.meta?.date ?? "") >= cutoff);

const chunks: unknown[] = [];
for (const { doc, chunks: cs } of chunkCorpus(kept)) {
  for (const c of cs) {
    chunks.push([c.collection, doc.title, c.section, c.pageStart, c.pageEnd, c.url ?? doc.url, c.content]);
  }
}
const counts: Record<string, number> = {};
for (const c of chunks as string[][]) counts[c[0]] = (counts[c[0]] ?? 0) + 1;
const updatedAt = docs.reduce((m, d) => (d.fetchedAt > m ? d.fetchedAt : m), "");
const payload = {
  sources: kept.length,
  updatedAt,
  collections: COLLECTIONS.map((c) => ({ ...c, chunks: counts[c.id] ?? 0 })),
  chunks,
  directory: buildDirectory(docs),
};
const json = JSON.stringify(payload);
const gz = gzipSync(json, { level: 9 }).toString("base64");
await mkdir("web/src/generated", { recursive: true });
await writeFile("web/src/generated/corpus-data.ts", `// Generated by scripts/export-static.ts. Do not edit.\nexport const CORPUS_GZ_BASE64 = "${gz}";\n`);
console.log(`${kept.length} sources, ${chunks.length} chunks: ${(json.length / 1e6).toFixed(1)} MB JSON -> ${(gz.length / 1e6).toFixed(1)} MB gzipped+base64`);
